/**
 * @file LogoArt.h
 * @brief The Hudson, Warped and TIVIDY logos as terminal art (half-block characters), one variant per ColorDepth.
 */

#ifndef TIVIDY_UI_LOGOART_H
#define TIVIDY_UI_LOGOART_H

#include <string>

#include "ui/ColorDepth.h"

namespace tividy
{

	/**
	 * @brief The logos, ready to print. Each is a block of lines ending in "\n". The data is generated by tools/make_logo_art.py
	 * from the images in docs/assets/clients/ and compiled into the program, so nothing is read from disk at run time.
	 *
	 * Every line is at most 80 columns wide. The coloured variants end each line with ESC[0m, so colour never leaks into later text.
	 * The logos have no "powered by TIVIDY" line: print ClientProfile::tagline under the art instead (it is too small to read as pixels).
	 */
	std::string hudsonLogo(ColorDepth depth);
	std::string warpedLogo(ColorDepth depth);
	std::string tividyLogo(ColorDepth depth);   /**< For the demo pack, which is TIVIDY itself. */
} // namespace tividy

#endif // TIVIDY_UI_LOGOART_H
